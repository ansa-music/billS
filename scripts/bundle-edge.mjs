// Bundles the shared cloud core for Supabase Edge Functions:
//   apps/cloud/src/edge/index.ts (+ sync, projection, settings, push, @bills/domain)
//   → supabase/functions/_shared/core.js  (ESM, es2022, `node:*` builtins left as imports).
// Deno runs it as is (node:crypto, node:buffer are supported). The file is generated:
// run `node scripts/bundle-edge.mjs` before `supabase functions deploy`.
import { build } from 'esbuild';
import { statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const entry = fileURLToPath(new URL('apps/cloud/src/edge/index.ts', root));
const outfile = fileURLToPath(new URL('supabase/functions/_shared/core.js', root));

const result = await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'es2022',
  // Builtins stay imports; Deno needs the `node:` prefix, which the sources already use.
  external: ['node:*'],
  // `Buffer`/`process` are globals in Node only: make them module imports for Deno.
  banner: {
    js: [
      '// GENERATED by scripts/bundle-edge.mjs from apps/cloud/src — do not edit.',
      "import { Buffer } from 'node:buffer';",
      "import process from 'node:process';",
    ].join('\n'),
  },
  legalComments: 'none',
  logLevel: 'warning',
  metafile: true,
});

const bare = Object.values(result.metafile.outputs)
  .flatMap((o) => o.imports)
  .filter((i) => i.external && !i.path.startsWith('node:'))
  .map((i) => i.path);
if (bare.length) {
  console.error(`bundle-edge: imports Deno cannot resolve: ${[...new Set(bare)].join(', ')}`);
  process.exit(1);
}
console.log(`bundle-edge: ${outfile} (${Math.round(statSync(outfile).size / 1024)} KB)`);
