/*
 * config.h — все настройки контроллера esp32-relay в одном месте.
 *
 * Перед прошивкой проверь:
 *   1. Сеть: Wi-Fi или Ethernet (USE_ETHERNET), SSID/пароль, статический IP.
 *   2. API_TOKEN — тот же токен нужно указать в настройках HUB.
 *   3. Пины реле и датчиков тока — должны совпадать с монтажом.
 *   4. RELAY_ACTIVE_LOW — зависит от модуля реле (большинство китайских
 *      модулей с оптронами включаются НИЗКИМ уровнем → 1).
 *   5. CURRENT_SENSOR_MV_PER_A и порог тока — под ваш датчик и лампы.
 */
#pragma once

#include <stdint.h>

// ============================================================================
// Устройство
// ============================================================================

// Идентификатор, который контроллер отдаёт в GET /status и использует как имя
// хоста в сети. Если контроллеров несколько — дай каждому своё имя
// (например "esp32-relay-1"), это удобно при поиске в роутере.
#define DEVICE_ID   "esp32-relay"
#define FW_VERSION  "1.0.0"

// ============================================================================
// Сеть
// ============================================================================

// Раскомментируй, чтобы работать через Ethernet (модуль W5500 по SPI) вместо
// Wi-Fi. Ethernet надёжнее для зала с десятками телефонов гостей.
// ВНИМАНИЕ: в режиме Ethernet меняется раскладка пинов, см. ниже.
// #define USE_ETHERNET

// Wi-Fi (используется, если USE_ETHERNET не задан). Сеть должна быть 2,4 ГГц.
#define WIFI_SSID      "club-wifi"
#define WIFI_PASSWORD  "change-me"

// Через сколько миллисекунд повторять попытку подключения к Wi-Fi.
#define WIFI_RECONNECT_MS  15000

// 0 — статический адрес (рекомендуется: HUB обращается к контроллеру по IP),
// 1 — получать адрес по DHCP (тогда закрепи адрес за MAC в роутере).
#define NET_USE_DHCP   0

// Статический адрес. Записывается через запятую, без точек!
// В HUB адрес канала выглядит как  esp32:192.168.1.50/<номер реле>
#define NET_IP         192, 168, 1, 50
#define NET_GATEWAY    192, 168, 1, 1
#define NET_SUBNET     255, 255, 255, 0
#define NET_DNS        192, 168, 1, 1

// Пины модуля W5500 (только для USE_ETHERNET). Это стандартная шина VSPI ESP32.
#define ETH_SPI_HOST   SPI3_HOST
#define ETH_PHY_ADDR   1       // для W5500 всегда 1
#define ETH_SPI_CS     5
#define ETH_SPI_IRQ    4       // INT модуля; обязателен
#define ETH_SPI_RST    -1      // RST модуля; -1 если не подключён (у модуля своя RC-цепочка сброса)
#define ETH_SPI_SCK    18
#define ETH_SPI_MISO   19
#define ETH_SPI_MOSI   23

// ============================================================================
// HTTP API
// ============================================================================

#define HTTP_PORT  80

// Токен доступа. Пустая строка — без авторизации (только для стенда!).
// Если задан, каждый запрос должен содержать заголовок
//   Authorization: Bearer <токен>
// (для проверки с телефона допускается ?token=<токен> в адресе).
#define API_TOKEN  ""

// ============================================================================
// Реле
// ============================================================================

#define RELAY_COUNT  8

// 1 — реле включается НИЗКИМ уровнем (типовые модули с оптронами, вход IN1..IN8);
// 0 — реле включается ВЫСОКИМ уровнем (модули с транзисторными ключами, SSR).
#define RELAY_ACTIVE_LOW  1

// Пины реле, канал 1..8 слева направо. Выбраны безопасные GPIO ESP32:
// не strapping-пины (0, 2, 5, 12, 15), не флеш (6–11), не input-only (34–39).
#ifdef USE_ETHERNET
// W5500 занимает 18, 19, 23 (SPI), 5 (CS), 4 (IRQ) — реле 5 и 6 переехали на 32/33.
static const int8_t RELAY_PINS[RELAY_COUNT] = { 13, 14, 16, 17, 21, 22, 32, 33 };
#else
static const int8_t RELAY_PINS[RELAY_COUNT] = { 13, 14, 16, 17, 18, 19, 21, 22 };
#endif

// ============================================================================
// Датчики тока
// ============================================================================

// Аналоговый вход датчика для каждого канала, -1 — датчика нет (в /status
// для такого канала currentOn = null).
//
// При Wi-Fi работает ТОЛЬКО ADC1 (GPIO 32, 33, 34, 35, 36, 39) — это 6 входов,
// поэтому по умолчанию датчики есть у каналов 1–6. Варианты для 8 датчиков —
// в README («Датчики тока»).
//
// При Ethernet Wi-Fi выключен, и доступен ADC2 (GPIO 25, 26, 27, 15 …) — 8 датчиков.
#ifdef USE_ETHERNET
static const int8_t CURRENT_PINS[RELAY_COUNT] = { 36, 39, 34, 35, 25, 26, 27, 15 };
#else
static const int8_t CURRENT_PINS[RELAY_COUNT] = { 36, 39, 34, 35, 32, 33, -1, -1 };
#endif

// Чувствительность датчика, мВ на ампер:
//   ACS712-05B → 185      ACS712-20A → 100      ACS712-30A → 66
//   SCT-013-030 с модулем (выход 1 В на 30 А) → 33
#define CURRENT_SENSOR_MV_PER_A  185

// Порог «ток есть» в миллиамперах (измеренный RMS ≥ порога → currentOn = true).
// Лампа накаливания 100 Вт ≈ 450 мА, светодиодный светильник 30 Вт ≈ 150–200 мА.
#define CURRENT_ON_THRESHOLD_MA   150
// Порог «тока нет» — ниже порога включения, чтобы значение не дребезжало.
#define CURRENT_OFF_THRESHOLD_MA  100

// Окно измерения RMS, мс. 100 мс = 5 периодов сети 50 Гц.
#define CURRENT_WINDOW_MS  100

// Калибровка нуля при включении: пока реле канала выключено, измеряется
// собственный шум датчика и АЦП и затем вычитается из показаний.
// 1 — автоматически при каждом включении (для каналов, у которых реле было
//     выключено; результат запоминается в NVS и используется, если при
//     следующем включении реле уже горит);
// 0 — фиксированное значение CURRENT_NOISE_FLOOR_MA для всех каналов.
#define CURRENT_AUTO_ZERO       1
#define CURRENT_NOISE_FLOOR_MA  0

// ============================================================================
// Прочее
// ============================================================================

// Светодиод статуса сети: мигает — сети нет, горит — сеть есть. -1 — нет светодиода.
// GPIO 2 — встроенный светодиод на большинстве плат ESP32 DevKit.
#define STATUS_LED_PIN         2
#define STATUS_LED_ACTIVE_LOW  0

// Сторожевой таймер, секунд. 0 — выключен. Только перезагружает ESP32 при
// зависании программы; состояние реле после перезагрузки восстанавливается
// из NVS, так что лампы над столами не гаснут.
#define WDT_TIMEOUT_S  30

// Мигание по умолчанию (POST /relay/<ch>/blink без параметров) и границы.
#define BLINK_DEFAULT_TIMES   3
#define BLINK_DEFAULT_ON_MS   400
#define BLINK_DEFAULT_OFF_MS  400
#define BLINK_MIN_TIMES       1
#define BLINK_MAX_TIMES       20
#define BLINK_MIN_MS          100
#define BLINK_MAX_MS          5000
